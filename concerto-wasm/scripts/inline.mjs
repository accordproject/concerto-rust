// Writes the loaders of the optimised module, pkg/concerto_wasm.wasm, and
// the package.json that names them `@accordproject/concerto-engine`:
//
//   pkg/concerto-engine.cjs       Node `require`: wasm-bindgen's `nodejs`
//                                 glue, reading the raw .wasm next to it
//                                 with readFileSync
//   pkg/concerto-engine.node.mjs  Node `import`: the `web` glue,
//                                 instantiated with `initSync` from the raw
//                                 .wasm, read with readFileSync
//   pkg/concerto-engine.mjs       browsers (BC-32): the `web` glue, not
//                                 instantiated until `await init()`, which
//                                 fetches and compiles the raw .wasm
//
// The package holds the module once: pkg/concerto_wasm.wasm, which all three
// loaders read. The `web` glue's unoptimised copy (pkg/web/concerto_wasm_bg.wasm)
// is removed, and the glue's default URL is pointed at the shipped file, so a
// bundler that follows the glue's `new URL(..., import.meta.url)` finds it.
//
// The Node loaders are ready as soon as they are loaded: Node reads and
// compiles the raw .wasm synchronously. Their `init()` resolves at once.
//
// The browser loader is not ready until `init()` resolves. `init()` loads
// `new URL('./concerto_wasm.wasm', import.meta.url)` with wasm-bindgen's
// loader (instantiateStreaming when the server sends application/wasm), or
// what `init({ module_or_path })` names: a URL or path, a Response, the
// bytes, or a compiled WebAssembly.Module. It is idempotent: every call
// returns the same promise, and later options are ignored. A failed load is
// not remembered, so `init()` can be called again. `setHost` may be called
// before `init()`: the factory is kept and registered once the module is
// instantiated, so concerto-core can be imported before `init()` runs. Any
// other engine call before `init()` resolves throws.
import { readFileSync, writeFileSync, rmSync } from 'node:fs';

const NAME = 'concerto_wasm';
const pkg = new URL('../pkg/', import.meta.url);
const wasm = readFileSync(new URL(`${NAME}.wasm`, pkg));

// The `web` glue: its default module URL names the shipped .wasm, and its
// own unoptimised copy goes.
const webGlueUrl = new URL(`web/${NAME}.js`, pkg);
const webGlue = readFileSync(webGlueUrl, 'utf8');
const defaultUrl = `new URL('${NAME}_bg.wasm', import.meta.url)`;
if (!webGlue.includes(defaultUrl)) {
  throw new Error('web glue changed shape: default module URL not found');
}
writeFileSync(webGlueUrl, webGlue.replace(defaultUrl, `new URL('../${NAME}.wasm', import.meta.url)`));
rmSync(new URL(`web/${NAME}_bg.wasm`, pkg));
rmSync(new URL(`web/${NAME}_bg.wasm.d.ts`, pkg));
writeFileSync(new URL('web/package.json', pkg), '{ "type": "module" }\n');

writeFileSync(new URL('concerto-engine.mjs', pkg), `// Generated by concerto-wasm/scripts/inline.mjs.
// Browsers: call \`await init()\` before using the engine. See README.md.
import initWasm, { setHost as registerHost } from './web/${NAME}.js';
let ready;
let instantiated = false;
let host;
// Kept until the module is instantiated, so it can be set before init().
export function setHost(errorFactory) {
  host = errorFactory;
  if (instantiated) registerHost(errorFactory);
}
// Loads, compiles and instantiates the engine, once: every call returns the
// same promise. \`module_or_path\` defaults to the .wasm next to this file.
export function init(options) {
  if (ready === undefined) {
    const module_or_path = options?.module_or_path ?? new URL('./${NAME}.wasm', import.meta.url);
    ready = initWasm({ module_or_path }).then(() => {
      instantiated = true;
      if (host !== undefined) registerHost(host);
    }, (err) => {
      ready = undefined;
      throw err;
    });
  }
  return ready;
}
export * from './web/${NAME}.js';
`);

// Node, both forms: the raw module read synchronously from pkg/, next to
// the loaders.
writeFileSync(new URL('concerto-engine.node.mjs', pkg), `// Generated by concerto-wasm/scripts/inline.mjs.
import { readFileSync } from 'node:fs';
import { initSync } from './web/${NAME}.js';
// Node compiles synchronously at any size: the module is ready once imported.
initSync({ module: readFileSync(new URL('./${NAME}.wasm', import.meta.url)) });
export async function init() {}
export * from './web/${NAME}.js';
`);

const glue = readFileSync(new URL(`node/${NAME}.js`, pkg), 'utf8');
const needle = `const wasmPath = \`\${__dirname}/${NAME}_bg.wasm\`;`;
if (!glue.includes(needle)) {
  throw new Error('nodejs glue changed shape: wasmPath line not found');
}
writeFileSync(new URL('concerto-engine.cjs', pkg), `// Generated by concerto-wasm/scripts/inline.mjs.\n${glue
  .replace(needle, `const wasmPath = \`\${__dirname}/${NAME}.wasm\`;`)}
// Node compiles synchronously at any size: the module is ready once required.
module.exports.init = async function init() {};
`);
rmSync(new URL('node/', pkg), { recursive: true });

writeFileSync(new URL('package.json', pkg), `${JSON.stringify({
  name: '@accordproject/concerto-engine',
  private: true,
  version: '0.0.0',
  description: 'The concerto-core Rust engine as WASM (concerto-rust concerto-wasm); linked locally, not published',
  license: 'Apache-2.0',
  main: 'concerto-engine.cjs',
  module: 'concerto-engine.mjs',
  exports: {
    browser: './concerto-engine.mjs',
    node: { import: './concerto-engine.node.mjs', require: './concerto-engine.cjs' },
    import: './concerto-engine.mjs',
    require: './concerto-engine.cjs',
  },
}, null, 2)}\n`);

console.log(`inline.mjs: ${wasm.length} bytes of wasm in pkg/${NAME}.wasm, the package's one copy`);
